CREATE TABLE `songs_history` (
  `history_id` int(11) NOT NULL AUTO_INCREMENT,
  `song_id` int(11) NOT NULL,
  `action` enum('initial','add','edit','delete') NOT NULL,
  `changed_by` varchar(50) DEFAULT NULL,
  `changed_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `category` int(11) DEFAULT NULL,
  `title` varchar(60) NOT NULL,
  `artist` varchar(60) DEFAULT NULL,
  `capo` int(11) DEFAULT NULL,
  `capo_alt` int(11) DEFAULT NULL,
  `owner` varchar(50) DEFAULT NULL,
  `is_public` tinyint(1) NOT NULL DEFAULT 1,
  `create_date` datetime DEFAULT NULL,
  `modified_date` datetime DEFAULT NULL,
  `tags` varchar(255) DEFAULT NULL,
  `instruments` varchar(255) DEFAULT NULL,
  `content` mediumtext DEFAULT NULL,
  `is_fixed` tinyint(1) NOT NULL DEFAULT 0,
  `is_nsfw` tinyint(1) NOT NULL DEFAULT 0,
  `youtube_link` varchar(255) DEFAULT NULL,
  `views` int(11) NOT NULL DEFAULT 0,
  PRIMARY KEY (`history_id`),
  KEY `song_id` (`song_id`),
  KEY `song_id_changed_at` (`song_id`,`changed_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
